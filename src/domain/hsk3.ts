export interface Word {
  hanzi: string;
  pinyin: string;
  meaning: string;
}
export const HSK3: Word[] = RAW.split("\n").map((l) => {
  const [hanzi, pinyin, meaning] = l.split("|");
  return { hanzi, pinyin, meaning };
});

/** First day of the series: the first word shows on this date. */
const START_DATE = Date.UTC(2026, 10, 27);

export function wordOfDay(isoDate: string): { word: Word; index: number } {
  const [y, m, d] = isoDate.split("-").map(Number);
  const n = Math.floor((Date.UTC(y, m - 1, d) - START_DATE) / 86400000);
  const index = ((n % HSK3.length) + HSK3.length) % HSK3.length;
  return { word: HSK3[index], index };
}
